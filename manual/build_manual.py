def shade_cell(cell, hex_fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tcPr.append(shd)


def add_field(paragraph, instr_text, placeholder_text=""):
    """Insert a raw OOXML field code (TOC, PAGE, NUMPAGES, ...) into a run."""
    run = paragraph.add_run()
    r = run._r

    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")

    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = instr_text

    separate = OxmlElement("w:fldChar")
    separate.set(qn("w:fldCharType"), "separate")

    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")

    r.append(begin)
    r.append(instr)
    if placeholder_text:
        t = OxmlElement("w:t")
        t.text = placeholder_text
        r.append(separate)
        r.append(t)
    else:
        r.append(separate)
    r.append(end)
    return run


def set_page_a4(doc, margin_cm=2.2):
    section = doc.sections[0]
    section.page_width = Cm(21.0)
    section.page_height = Cm(29.7)
    section.left_margin = Cm(margin_cm)
    section.right_margin = Cm(margin_cm)
    section.top_margin = Cm(1.8)
    section.bottom_margin = Cm(1.8)


def add_footer(doc):
    section = doc.sections[0]
    footer = section.footer
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(f"{APP_NAME} — User Manual  ·  Page ")
    run.font.size = Pt(9)
    run.font.color.rgb = GREY
    add_field(p, "PAGE", "1")
    run2 = p.add_run(" of ")
    run2.font.size = Pt(9)
    run2.font.color.rgb = GREY
    add_field(p, "NUMPAGES", "1")
    for r in p.runs:
        r.font.size = Pt(9)
        r.font.color.rgb = GREY


